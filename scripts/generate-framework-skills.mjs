import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDirectory = join(root, "skills", "frameworks");
const outputPath = join(root, "src", "framework-skills.generated.ts");
const check = process.argv.includes("--check");

const entries = await readdir(skillsDirectory, { withFileTypes: true });
const skills = {};

for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue;
  skills[entry.name] = await readFile(join(skillsDirectory, entry.name, "SKILL.md"), "utf8");
}

const generated = [
  "// Generated by scripts/generate-framework-skills.mjs. Do not edit directly.",
  `export const FRAMEWORK_SKILL_CONTENT = ${JSON.stringify(skills, null, 2)} as const;`,
  "",
].join("\n");

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error("Bundled framework skills are stale. Run npm run frameworks:generate.");
  }
} else {
  await writeFile(outputPath, generated);
}
